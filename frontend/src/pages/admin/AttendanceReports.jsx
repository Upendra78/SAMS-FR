import DataTable from "../../components/DataTable";
import PageState from "../../components/PageState";

function AttendanceReports() {
  const reports = [];

  const columns = [
    { key: "date", label: "Date" },
    { key: "class", label: "Class" },
    { key: "present", label: "Present" },
    { key: "absent", label: "Absent" },
    { key: "percentage", label: "Attendance %" },
  ];

  return (
    <section>
      <h1>Attendance Reports</h1>

      <p>
        View attendance reports generated by the SAMS-FR system.
      </p>

      {reports.length === 0 ? (
        <PageState
          title="No attendance reports available"
          message="Attendance report data will be displayed here when it is provided by the backend."
        />
      ) : (
        <DataTable
          columns={columns}
          data={reports}
          emptyMessage="No attendance reports found."
        />
      )}
    </section>
  );
}

export default AttendanceReports;